CREATE TABLE [Salesforce].[Account]
(
    [Id] NVARCHAR(18) NOT NULL,
    [IsDeleted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Account_IsDeleted] DEFAULT (0),
    [ParentId] NVARCHAR(18) NULL,
    [Name] NVARCHAR(255) NOT NULL,
    [Type] NVARCHAR(40) NULL,
    [BillingStreet] NVARCHAR(255) NULL,
    [BillingCity] NVARCHAR(40) NULL,
    [BillingState] NVARCHAR(80) NULL,
    [BillingPostalCode] NVARCHAR(20) NULL,
    [BillingCountry] NVARCHAR(80) NULL,
    [ShippingStreet] NVARCHAR(255) NULL,
    [ShippingCity] NVARCHAR(40) NULL,
    [ShippingState] NVARCHAR(80) NULL,
    [ShippingPostalCode] NVARCHAR(20) NULL,
    [ShippingCountry] NVARCHAR(80) NULL,
    [Phone] NVARCHAR(40) NULL,
    [Fax] NVARCHAR(40) NULL,
    [Website] NVARCHAR(255) NULL,
    [Industry] NVARCHAR(40) NULL,
    [AnnualRevenue] DECIMAL(18, 2) NULL,
    [NumberOfEmployees] INT NULL,
    [Description] NVARCHAR(MAX) NULL,
    [OwnerId] NVARCHAR(18) NOT NULL,
    [CreatedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Account_CreatedDate] DEFAULT (SYSUTCDATETIME()),
    [CreatedById] NVARCHAR(18) NOT NULL,
    [LastModifiedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Account_LastModifiedDate] DEFAULT (SYSUTCDATETIME()),
    [LastModifiedById] NVARCHAR(18) NOT NULL,
    CONSTRAINT [PK_Salesforce_Account] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Salesforce_Account_ParentId] FOREIGN KEY ([ParentId]) REFERENCES [Salesforce].[Account] ([Id]),
    CONSTRAINT [FK_Salesforce_Account_OwnerId] FOREIGN KEY ([OwnerId]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Account_CreatedById] FOREIGN KEY ([CreatedById]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Account_LastModifiedById] FOREIGN KEY ([LastModifiedById]) REFERENCES [Salesforce].[User] ([Id])
);
