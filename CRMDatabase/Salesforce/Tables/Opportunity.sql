CREATE TABLE [Salesforce].[Opportunity]
(
    [Id] NVARCHAR(18) NOT NULL,
    [IsDeleted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_IsDeleted] DEFAULT (0),
    [AccountId] NVARCHAR(18) NULL,
    [IsPrivate] BIT NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_IsPrivate] DEFAULT (0),
    [Name] NVARCHAR(120) NOT NULL,
    [Description] NVARCHAR(MAX) NULL,
    [StageName] NVARCHAR(40) NOT NULL,
    [Amount] DECIMAL(18, 2) NULL,
    [Probability] DECIMAL(5, 2) NULL,
    [ExpectedRevenue] AS (CAST([Amount] * ([Probability] / 100.0) AS DECIMAL(18, 2))),
    [CloseDate] DATE NOT NULL,
    [Type] NVARCHAR(40) NULL,
    [LeadSource] NVARCHAR(40) NULL,
    [IsClosed] BIT NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_IsClosed] DEFAULT (0),
    [IsWon] BIT NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_IsWon] DEFAULT (0),
    [ForecastCategoryName] NVARCHAR(40) NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_ForecastCategoryName] DEFAULT (N'Pipeline'),
    [CampaignId] NVARCHAR(18) NULL,
    [Pricebook2Id] NVARCHAR(18) NULL,
    [OwnerId] NVARCHAR(18) NOT NULL,
    [CreatedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_CreatedDate] DEFAULT (SYSUTCDATETIME()),
    [CreatedById] NVARCHAR(18) NOT NULL,
    [LastModifiedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Opportunity_LastModifiedDate] DEFAULT (SYSUTCDATETIME()),
    [LastModifiedById] NVARCHAR(18) NOT NULL,
    CONSTRAINT [PK_Salesforce_Opportunity] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Salesforce_Opportunity_AccountId] FOREIGN KEY ([AccountId]) REFERENCES [Salesforce].[Account] ([Id]),
    CONSTRAINT [FK_Salesforce_Opportunity_CampaignId] FOREIGN KEY ([CampaignId]) REFERENCES [Salesforce].[Campaign] ([Id]),
    CONSTRAINT [FK_Salesforce_Opportunity_Pricebook2Id] FOREIGN KEY ([Pricebook2Id]) REFERENCES [Salesforce].[Pricebook2] ([Id]),
    CONSTRAINT [FK_Salesforce_Opportunity_OwnerId] FOREIGN KEY ([OwnerId]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Opportunity_CreatedById] FOREIGN KEY ([CreatedById]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Opportunity_LastModifiedById] FOREIGN KEY ([LastModifiedById]) REFERENCES [Salesforce].[User] ([Id])
);
