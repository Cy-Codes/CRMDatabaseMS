CREATE TABLE [Salesforce].[Case]
(
    [Id] NVARCHAR(18) NOT NULL,
    [IsDeleted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Case_IsDeleted] DEFAULT (0),
    [CaseNumber] NVARCHAR(30) NOT NULL,
    [ContactId] NVARCHAR(18) NULL,
    [AccountId] NVARCHAR(18) NULL,
    [ParentId] NVARCHAR(18) NULL,
    [SuppliedName] NVARCHAR(80) NULL,
    [SuppliedEmail] NVARCHAR(128) NULL,
    [SuppliedPhone] NVARCHAR(40) NULL,
    [SuppliedCompany] NVARCHAR(80) NULL,
    [Type] NVARCHAR(40) NULL,
    [Status] NVARCHAR(40) NOT NULL CONSTRAINT [DF_Salesforce_Case_Status] DEFAULT (N'New'),
    [Reason] NVARCHAR(40) NULL,
    [Origin] NVARCHAR(40) NULL,
    [Subject] NVARCHAR(255) NULL,
    [Priority] NVARCHAR(40) NOT NULL CONSTRAINT [DF_Salesforce_Case_Priority] DEFAULT (N'Medium'),
    [Description] NVARCHAR(MAX) NULL,
    [IsClosed] BIT NOT NULL CONSTRAINT [DF_Salesforce_Case_IsClosed] DEFAULT (0),
    [ClosedDate] DATETIME2 NULL,
    [IsEscalated] BIT NOT NULL CONSTRAINT [DF_Salesforce_Case_IsEscalated] DEFAULT (0),
    [OwnerId] NVARCHAR(18) NOT NULL,
    [CreatedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Case_CreatedDate] DEFAULT (SYSUTCDATETIME()),
    [CreatedById] NVARCHAR(18) NOT NULL,
    [LastModifiedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Case_LastModifiedDate] DEFAULT (SYSUTCDATETIME()),
    [LastModifiedById] NVARCHAR(18) NOT NULL,
    CONSTRAINT [PK_Salesforce_Case] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Salesforce_Case_ContactId] FOREIGN KEY ([ContactId]) REFERENCES [Salesforce].[Contact] ([Id]),
    CONSTRAINT [FK_Salesforce_Case_AccountId] FOREIGN KEY ([AccountId]) REFERENCES [Salesforce].[Account] ([Id]),
    CONSTRAINT [FK_Salesforce_Case_ParentId] FOREIGN KEY ([ParentId]) REFERENCES [Salesforce].[Case] ([Id]),
    CONSTRAINT [FK_Salesforce_Case_OwnerId] FOREIGN KEY ([OwnerId]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Case_CreatedById] FOREIGN KEY ([CreatedById]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Case_LastModifiedById] FOREIGN KEY ([LastModifiedById]) REFERENCES [Salesforce].[User] ([Id])
);
