CREATE TABLE [Salesforce].[Contact]
(
    [Id] NVARCHAR(18) NOT NULL,
    [IsDeleted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Contact_IsDeleted] DEFAULT (0),
    [AccountId] NVARCHAR(18) NULL,
    [LastName] NVARCHAR(80) NOT NULL,
    [FirstName] NVARCHAR(40) NULL,
    [Salutation] NVARCHAR(40) NULL,
    [Name] AS (ISNULL([FirstName] + N' ', N'') + [LastName]),
    [ReportsToId] NVARCHAR(18) NULL,
    [Title] NVARCHAR(128) NULL,
    [Department] NVARCHAR(80) NULL,
    [Email] NVARCHAR(128) NULL,
    [Phone] NVARCHAR(40) NULL,
    [MobilePhone] NVARCHAR(40) NULL,
    [MailingStreet] NVARCHAR(255) NULL,
    [MailingCity] NVARCHAR(40) NULL,
    [MailingState] NVARCHAR(80) NULL,
    [MailingPostalCode] NVARCHAR(20) NULL,
    [MailingCountry] NVARCHAR(80) NULL,
    [LeadSource] NVARCHAR(40) NULL,
    [Description] NVARCHAR(MAX) NULL,
    [OwnerId] NVARCHAR(18) NOT NULL,
    [CreatedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Contact_CreatedDate] DEFAULT (SYSUTCDATETIME()),
    [CreatedById] NVARCHAR(18) NOT NULL,
    [LastModifiedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Contact_LastModifiedDate] DEFAULT (SYSUTCDATETIME()),
    [LastModifiedById] NVARCHAR(18) NOT NULL,
    CONSTRAINT [PK_Salesforce_Contact] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Salesforce_Contact_AccountId] FOREIGN KEY ([AccountId]) REFERENCES [Salesforce].[Account] ([Id]),
    CONSTRAINT [FK_Salesforce_Contact_ReportsToId] FOREIGN KEY ([ReportsToId]) REFERENCES [Salesforce].[Contact] ([Id]),
    CONSTRAINT [FK_Salesforce_Contact_OwnerId] FOREIGN KEY ([OwnerId]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Contact_CreatedById] FOREIGN KEY ([CreatedById]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Contact_LastModifiedById] FOREIGN KEY ([LastModifiedById]) REFERENCES [Salesforce].[User] ([Id])
);
