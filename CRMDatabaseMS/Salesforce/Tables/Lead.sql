CREATE TABLE [Salesforce].[Lead]
(
    [Id] NVARCHAR(18) NOT NULL,
    [IsDeleted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Lead_IsDeleted] DEFAULT (0),
    [LastName] NVARCHAR(80) NOT NULL,
    [FirstName] NVARCHAR(40) NULL,
    [Salutation] NVARCHAR(40) NULL,
    [Name] AS (ISNULL([FirstName] + N' ', N'') + [LastName]),
    [Title] NVARCHAR(128) NULL,
    [Company] NVARCHAR(255) NOT NULL,
    [Street] NVARCHAR(255) NULL,
    [City] NVARCHAR(40) NULL,
    [State] NVARCHAR(80) NULL,
    [PostalCode] NVARCHAR(20) NULL,
    [Country] NVARCHAR(80) NULL,
    [Phone] NVARCHAR(40) NULL,
    [MobilePhone] NVARCHAR(40) NULL,
    [Email] NVARCHAR(128) NULL,
    [Website] NVARCHAR(255) NULL,
    [LeadSource] NVARCHAR(40) NULL,
    [Status] NVARCHAR(40) NOT NULL CONSTRAINT [DF_Salesforce_Lead_Status] DEFAULT (N'Open - Not Contacted'),
    [Industry] NVARCHAR(40) NULL,
    [AnnualRevenue] DECIMAL(18, 2) NULL,
    [NumberOfEmployees] INT NULL,
    [Description] NVARCHAR(MAX) NULL,
    [IsConverted] BIT NOT NULL CONSTRAINT [DF_Salesforce_Lead_IsConverted] DEFAULT (0),
    [ConvertedDate] DATE NULL,
    [ConvertedAccountId] NVARCHAR(18) NULL,
    [ConvertedContactId] NVARCHAR(18) NULL,
    [ConvertedOpportunityId] NVARCHAR(18) NULL,
    [IsUnreadByOwner] BIT NOT NULL CONSTRAINT [DF_Salesforce_Lead_IsUnreadByOwner] DEFAULT (1),
    [OwnerId] NVARCHAR(18) NOT NULL,
    [CreatedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Lead_CreatedDate] DEFAULT (SYSUTCDATETIME()),
    [CreatedById] NVARCHAR(18) NOT NULL,
    [LastModifiedDate] DATETIME2 NOT NULL CONSTRAINT [DF_Salesforce_Lead_LastModifiedDate] DEFAULT (SYSUTCDATETIME()),
    [LastModifiedById] NVARCHAR(18) NOT NULL,
    CONSTRAINT [PK_Salesforce_Lead] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Salesforce_Lead_ConvertedAccountId] FOREIGN KEY ([ConvertedAccountId]) REFERENCES [Salesforce].[Account] ([Id]),
    CONSTRAINT [FK_Salesforce_Lead_ConvertedContactId] FOREIGN KEY ([ConvertedContactId]) REFERENCES [Salesforce].[Contact] ([Id]),
    CONSTRAINT [FK_Salesforce_Lead_OwnerId] FOREIGN KEY ([OwnerId]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Lead_CreatedById] FOREIGN KEY ([CreatedById]) REFERENCES [Salesforce].[User] ([Id]),
    CONSTRAINT [FK_Salesforce_Lead_LastModifiedById] FOREIGN KEY ([LastModifiedById]) REFERENCES [Salesforce].[User] ([Id])
);
